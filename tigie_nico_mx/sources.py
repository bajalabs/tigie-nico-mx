"""The official publications the edition is built from, pinned by the sha256 of their Word files.

The manifest is `sources.json` beside this file. Every file is the Cámara de Diputados' copy of a
DOF publication (LeyesBiblio, "Ley de los Impuestos Generales de Importación y de Exportación",
`ref/ligie_2022.htm`): the consolidated text (`doc/LIGIE_2022.doc`, regenerated by the Cámara on
14-10-2026 after the decree of DOF 13-10-2026) and, under `ref/ligie_2022/`, the law as first
published, its two reforms, the sixteen decrees that modify its Tarifa, and the three acuerdos of
the Secretaría de Economía on NICOs. The DOF note numbers (`codNota`) come from SIDOF's daily index.
The Cámara's copies are "sólo de carácter informativo"; the DOF edition is the official one.

A capture is a folder holding each Word file at its published path (`LIGIE_2022.doc`,
`ligie_2022/<name>.doc`) with the LibreOffice HTML export beside it (`<name>.html`); `capture.py`
makes one. The build refuses a capture whose Word files differ from the pinned hashes (a new
Cámara regeneration means a new decree this package does not know yet) unless told to accept it.
"""

from __future__ import annotations

import hashlib
import json
from dataclasses import dataclass
from datetime import date
from functools import cache
from importlib import resources
from pathlib import Path
from typing import Any

from tigie_nico_mx.html import Item, read_items

MANIFEST_NAME = "sources.json"


def _manifest() -> dict[str, Any]:
    text = resources.files("tigie_nico_mx").joinpath(MANIFEST_NAME).read_text(encoding="utf-8")
    data: dict[str, Any] = json.loads(text)
    return data


MANIFEST = _manifest()
INDEX_URL: str = MANIFEST["index_url"]
LIGIE_IN_FORCE = date.fromisoformat(MANIFEST["ligie_in_force"])
LIGIE_IN_FORCE_SOURCE: str = MANIFEST["ligie_in_force_source"]
CONSOLIDATED_ON = date.fromisoformat(MANIFEST["consolidated_on"])


@dataclass(frozen=True)
class Source:
    key: str
    path: str  # the Word file inside the capture
    url: str
    dof: date
    cod_nota: int
    title: str
    sha256: str
    role: str = ""

    @property
    def html(self) -> str:
        return self.path.removesuffix(".doc") + ".html"

    @property
    def dof_rank(self) -> tuple[date, int]:
        """Order of publication (date, then the DOF's note number)."""
        return self.dof, self.cod_nota

    @property
    def authority(self) -> str:
        return f"DOF {self.dof:%d-%m-%Y} codNota {self.cod_nota}"

    @property
    def label(self) -> str:
        """`DOF dd-mm-yyyy: title`, the form of the `decreto` column."""
        return f"DOF {self.dof:%d-%m-%Y}: {self.title}"


SOURCES: dict[str, Source] = {
    f["key"]: Source(
        key=f["key"],
        path=f["file"],
        url=f["url"],
        dof=date.fromisoformat(f["dof"]),
        cod_nota=int(f["cod_nota"]),
        title=f["title"],
        sha256=f["sha256"],
        role=f.get("role", ""),
    )
    for f in MANIFEST["files"]
}


def sha256_file(path: Path) -> str:
    digest = hashlib.sha256()
    with path.open("rb") as handle:
        for chunk in iter(lambda: handle.read(1 << 20), b""):
            digest.update(chunk)
    return digest.hexdigest()


class Capture:
    """A folder of the Cámara's Word files and their HTML exports."""

    def __init__(self, root: Path) -> None:
        self.root = root

    def html_path(self, key: str) -> Path:
        return self.root / SOURCES[key].html

    @cache  # noqa: B019 - one capture per run; the cache lives as long as the run
    def items(self, key: str) -> list[Item]:
        path = self.html_path(key)
        if not path.is_file():
            raise FileNotFoundError(f"missing HTML export {SOURCES[key].html} in {self.root}")
        return read_items(path)

    def verify(self) -> list[dict[str, object]]:
        """One row per source: its Word file's sha256 against the pinned one."""
        rows: list[dict[str, object]] = []
        for source in SOURCES.values():
            doc = self.root / source.path
            row: dict[str, object] = {
                "key": source.key,
                "file": source.path,
                "dof": f"{source.dof:%Y-%m-%d}",
                "cod_nota": source.cod_nota,
                "url": source.url,
                "html": (self.root / source.html).is_file(),
            }
            if doc.is_file():
                actual = sha256_file(doc)
                row["sha256"] = actual
                row["pinned"] = actual == source.sha256
            else:
                row["sha256"] = None
                row["pinned"] = False
            rows.append(row)
        return rows
